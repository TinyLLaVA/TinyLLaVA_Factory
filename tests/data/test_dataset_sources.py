"""Exercise real local sources and the Hub loader contract without downloads."""

import io
import json
import os
from types import SimpleNamespace

import datasets
import pytest
import torch
from PIL import Image

import tinyllava.data.dataset as loading
from tinyllava.data.image_payload import collect_sample_image_payloads
from tinyllava.utils.arguments import DataArguments


def rows():
    return [
        {"id": str(i), "messages": [{"role": "user", "content": f"sample {i}"}]}
        for i in range(4)
    ]


@pytest.mark.parametrize("kind", ["jsonl", "parquet"])
def test_single_local_file_and_split(tmp_path, kind):
    path = tmp_path / f"samples.{kind}"
    if kind == "jsonl":
        path.write_text("\n".join(json.dumps(row) for row in rows()))
    else:
        datasets.Dataset.from_list(rows()).to_parquet(path)
    result = loading.load_training_dataset(
        DataArguments(
            dataset_name_or_path=str(path),
            split="train[1:3]",
            cache_dir=str(tmp_path / "cache"),
        )
    )
    assert result.to_list() == rows()[1:3]
    assert all(
        item["filename"].startswith(str(tmp_path / "cache"))
        for item in result.cache_files
    )


@pytest.mark.parametrize("builder", ["parquet", "directory"])
def test_multiple_files_and_named_split(tmp_path, builder):
    for i, row in enumerate(rows()):
        datasets.Dataset.from_list([row]).to_parquet(tmp_path / f"part-{i}.parquet")
    result = loading.load_training_dataset(
        DataArguments(
            dataset_name_or_path="parquet" if builder == "parquet" else str(tmp_path),
            data_files={"validation": str(tmp_path / "part-*.parquet")},
            split="validation[:50%]",
            cache_dir=str(tmp_path / "cache"),
        )
    )
    assert result.to_list() == rows()[:2]


def test_hub_arguments_are_forwarded(monkeypatch, tmp_path):
    calls = []

    def load(path, **kwargs):
        calls.append((path, kwargs))
        return datasets.Dataset.from_list(rows())

    monkeypatch.setattr(loading, "load_dataset", load)
    args = DataArguments(
        dataset_name_or_path="org/multimodal",
        dataset_config_name="charts",
        split="validation[:10%]",
        data_files={"validation": ["shard-*.parquet"]},
        data_dir="images",
        revision="commit-id",
        cache_dir=str(tmp_path / "cache"),
    )
    assert loading.load_training_dataset(args).to_list() == rows()
    assert calls == [
        (
            "org/multimodal",
            {
                "name": "charts",
                "split": "validation[:10%]",
                "data_files": {"validation": ["shard-*.parquet"]},
                "data_dir": "images",
                "revision": "commit-id",
                "cache_dir": str(tmp_path / "cache"),
            },
        )
    ]


@pytest.mark.parametrize(
    "split,expected",
    [
        ("train[1:3]", [1, 2]),
        ("train[:50%]", [0, 1]),
        ("train[:0]", []),
        ("train[:1]+train[-1:]", [0, 3]),
    ],
)
def test_native_json_array_uses_split_and_cache(tmp_path, split, expected):
    path = tmp_path / "samples.json"
    path.write_text(json.dumps(rows()))
    result = loading.load_training_dataset(
        DataArguments(
            dataset_name_or_path=str(path),
            split=split,
            cache_dir=str(tmp_path / "cache"),
        )
    )
    assert result.to_list() == [rows()[i] for i in expected]


def test_array_cache_reuses_then_invalidates_modified_source(tmp_path, monkeypatch):
    path = tmp_path / "samples.json"
    path.write_text(json.dumps(rows()))
    args = DataArguments(
        dataset_name_or_path=str(path), cache_dir=str(tmp_path / "cache")
    )
    first = loading.load_training_dataset(args)
    second = loading.load_training_dataset(args)
    assert first.cache_files == second.cache_files
    modified = rows()
    modified[0]["messages"][0]["content"] = "changed"
    old_mtime = path.stat().st_mtime_ns
    path.write_text(json.dumps(modified))
    os.utime(path, ns=(old_mtime + 1000000, old_mtime + 1000000))
    third = loading.load_training_dataset(args)
    assert third.to_list() == modified
    assert third.cache_files != first.cache_files
    # Dependency changes must not reuse a cache generated by an older parser.
    fingerprint = loading._json_array_fingerprint(path, None)
    monkeypatch.setattr(loading, "version", lambda name: "changed-parser")
    assert loading._json_array_fingerprint(path, None) != fingerprint


@pytest.mark.parametrize(
    "key,value",
    [
        ("revision", "main"),
        ("data_files", "other.json"),
        ("dataset_config_name", "subset"),
        ("data_dir", "folder"),
    ],
)
def test_direct_file_rejects_conflicting_options(tmp_path, key, value):
    path = tmp_path / "samples.json"
    path.write_text(json.dumps(rows()))
    with pytest.raises(ValueError, match="direct dataset file"):
        loading.load_training_dataset(
            DataArguments(dataset_name_or_path=str(path), **{key: value})
        )


def test_missing_path_and_split_validation(tmp_path):
    with pytest.raises(ValueError, match="dataset_name_or_path"):
        loading.load_training_dataset(DataArguments())
    with pytest.raises(FileNotFoundError):
        loading.load_training_dataset(
            DataArguments(dataset_name_or_path=str(tmp_path / "absent.json"))
        )
    with pytest.raises(ValueError, match="split"):
        loading.load_training_dataset(
            DataArguments(dataset_name_or_path="org/data", split=None)
        )


def test_parquet_embedded_images_reach_processor(tmp_path):
    path = tmp_path / "images.parquet"
    features = datasets.Features(
        {
            "image": datasets.Image(),
            "conversations": datasets.List(
                {"role": datasets.Value("string"), "content": datasets.Value("string")}
            ),
        }
    )
    # The first row has no image: detection must consult the full feature schema.
    datasets.Dataset.from_list(
        [
            {"image": None, "conversations": [{"role": "user", "content": "hello"}]},
            {
                "image": Image.new("RGB", (3, 2), "red"),
                "conversations": [
                    {"role": "user", "content": "<image>\nWhat color?"},
                    {"role": "assistant", "content": "red"},
                ],
            },
        ],
        features=features,
    ).to_parquet(path)
    data = loading.load_training_dataset(
        DataArguments(dataset_name_or_path=str(path), cache_dir=str(tmp_path / "cache"))
    )
    assert isinstance(data.features["image"], datasets.Image)

    def encode(messages, **kwargs):
        image = messages[0]["content"][0]["image"]
        assert image.size == (3, 2)
        assert image.getpixel((0, 0)) == (255, 0, 0)
        return {
            "input_ids": torch.tensor([[1, 2]]),
            "assistant_masks": torch.tensor([[0, 1]]),
        }

    wrapped = loading.ProcessorSFTDataset(
        data,
        SimpleNamespace(tokenizer=object(), apply_chat_template=encode),
        DataArguments(),
    )
    assert wrapped[1]["labels"].tolist() == [-100, 2]
    assert wrapped.modality_lengths[0] < 0 < wrapped.modality_lengths[1]


def test_image_lists_and_arrow_image_payloads(tmp_path):
    image = Image.new("RGB", (2, 3), "blue")
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    embedded = {"bytes": buffer.getvalue(), "path": None}
    payloads = collect_sample_image_payloads({"images": [image, embedded]})
    assert all(item.size == (2, 3) for item in payloads)
    image.save(tmp_path / "blue.png")
    payloads = collect_sample_image_payloads(
        {"image": {"bytes": None, "path": "blue.png"}}, str(tmp_path)
    )
    assert payloads[0].getpixel((0, 0)) == (0, 0, 255)


def test_native_conversation_content_blocks_are_preserved(tmp_path):
    source = [
        {
            "image": "image.png",
            "conversations": [
                {
                    "role": "user",
                    "content": [
                        {"type": "image"},
                        {"type": "text", "text": "Describe this."},
                    ],
                }
            ],
        }
    ]
    path = tmp_path / "native.json"
    path.write_text(json.dumps(source))
    result = loading.load_training_dataset(
        DataArguments(
            dataset_name_or_path=str(path),
            cache_dir=str(tmp_path / "cache"),
        )
    )
    blocks = result[0]["conversations"][0]["content"]
    assert blocks[0]["type"] == "image"
    assert blocks[1]["text"] == "Describe this."
    assert result[0]["image"] == "image.png"
